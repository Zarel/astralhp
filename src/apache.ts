import fs from "node:fs";
import path from "node:path";
import type { Adapter } from "./config.d.ts";
import { serverPort } from "./live-server.js";
import type { AstralHPResolvedRoutes, Webroot } from "./webroot.js";

const BEGIN_MARKER = "# ===== BEGIN ASTRALHP =====";
const END_MARKER = "# ===== END ASTRALHP =====";
const MARKER_PATTERN = /^# =* ?(BEGIN|END) ASTRALHP ?=*[ \t]*\r?$/gm;

function apachePort(): number {
	const port = serverPort();
	if (port === 0) {
		throw new Error("PORT must not be 0 when generating Apache configuration");
	}
	return port;
}

export interface ApacheRoute {
	pattern: string;
	regex: string;
}

function escapeRegex(source: string): string {
	return source.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

export function apacheRoute(
	route: AstralHPResolvedRoutes["routes"][number],
	trailingSlash: AstralHPResolvedRoutes["trailingSlash"],
): ApacheRoute {
	const rootSpread = route.segments.length === 1 &&
		route.segments[0]?.length === 1 &&
		route.segments[0][0]?.spread;
	let regex = "^";

	for (const [index, segment] of route.segments.entries()) {
		if (segment.length === 1 && segment[0]?.spread) {
			regex += index === 0 ? ".*?" : "(?:/.*?)?";
			continue;
		}
		if (index) regex += "/";
		for (const part of segment) {
			regex += part.spread ?
				".*?" :
				part.dynamic ?
				"[^/]+?" :
				escapeRegex(part.content.normalize());
		}
	}

	if (route.segments.length) {
		if (trailingSlash === "always") {
			if (rootSpread) return { pattern: route.pattern, regex: "^(?:.*?/)?$" };
			regex += "/";
		} else if (trailingSlash === "ignore") {
			regex += "/?";
		}
	}
	regex += "$";
	return { pattern: route.pattern, regex };
}

function proxyRules(port: number, routes: readonly ApacheRoute[]): string {
	if (!routes.length) return "";
	const patterns = [...new Map(
		routes.map(route => [route.regex, route]),
	).values()].sort((a, b) => a.pattern.localeCompare(b.pattern));
	const rules = patterns.map(route => {
		const regex = route.regex.replace(/"/g, '\\"');
		return `RewriteRule "${regex}" "http://127.0.0.1:${port}%{REQUEST_URI}" [P,END,NE]`;
	});
	return `# Identify this Apache webroot to the shared AstralHP server
RequestHeader set X-AstralHP-Document-Root "expr=%{DOCUMENT_ROOT}"

# Preserve the public hostname for Astro
ProxyPreserveHost On

# Proxy dynamic AstralHP routes
${rules.join("\n")}`;
}

function cgiRules(routes: readonly ApacheRoute[]): string {
	if (!routes.length) return "";
	const patterns = [...new Set(routes.map(route => route.regex))].sort();
	return `# Execute dynamic AstralHP routes through CGI
Options +ExecCGI
<Files "cgi.mjs">
    SetHandler cgi-script
</Files>
${
	patterns.map(regex => `RewriteRule "${regex.replace(/"/g, '\\"')}" ".caches/dist/.server/cgi.mjs" [END]`).join(
		"\n",
	)
}`;
}

export function apacheBlock(
	port?: number,
	routes: readonly ApacheRoute[] = [],
	adapter: Exclude<Adapter, "node"> = "apache-proxy",
	rootIndex?: string,
): string {
	const proxyPort = adapter === "apache-proxy" ? port ?? apachePort() : 0;
	if (adapter === "apache-proxy" && (!Number.isInteger(proxyPort) || proxyPort < 1 || proxyPort > 65535)) {
		throw new Error(`Invalid Apache proxy port: ${proxyPort}`);
	}
	if (adapter === "apache-static" && routes.length) {
		throw new Error(`apache-static does not support dynamic routes: ${routes.map(route => route.pattern).join(", ")}`);
	}
	const dynamic = adapter === "apache-static" ? "" :
		adapter === "apache-cgi" ? cgiRules(routes) :
		proxyRules(proxyPort, routes);
	const rootRule = rootIndex ? `RewriteRule "^$" ".caches/dist/${rootIndex}" [END]\n` : "";

	return `${BEGIN_MARKER}
# Generated by AstralHP. EDITS WILL BE OVERWRITTEN.

RewriteEngine On

# Don't allow .caches to be served
RewriteCond expr "tolower(unescape(%{THE_REQUEST})) =~ m#\\s/+\\.caches(?:/|%2f|\\?|\\s)#"
RewriteRule "^" "-" [R=404,END]

# Don't serve node_modules, dotfiles (except .well-known and .caches), or page and endpoint sources
RewriteRule "(?:^|/)node_modules(?:/|$)" "-" [R=404,END,NC]
RewriteRule "(?:^|/)\\.(?!well-known(?:/|$)|caches(?:/|$))" "-" [R=404,END,NC]
RewriteRule "\\.(?:astro(?:\\.[jt]s)?|mdx?)$" "-" [R=404,END,NC]

# Serve built files in .caches/dist/
${rootRule}RewriteCond "%{DOCUMENT_ROOT}/.caches/dist/$1" -f
RewriteRule "^(.+)$" ".caches/dist/$1" [END]

# Serve all other files
RewriteCond "%{REQUEST_FILENAME}" -f
RewriteRule "^" "-" [END]

# Remove .html from URLs
RewriteCond "%{DOCUMENT_ROOT}/.caches/dist/$1.html" -f
RewriteRule "^(.+?)/?$" ".caches/dist/$1.html" [END]

RewriteCond "%{DOCUMENT_ROOT}/.caches/dist/$1/index.html" -f
RewriteRule "^(.+?)/?$" ".caches/dist/$1/index.html" [END]${dynamic ? `\n\n${dynamic}` : ""}

${END_MARKER}`;
}

export function resolveApacheRoutes(
	resolved: AstralHPResolvedRoutes,
): ApacheRoute[] {
	const { routes, trailingSlash } = resolved;
	return routes
		.filter(route => (route.type === "page" || route.type === "endpoint") && !route.isPrerendered)
		.map(route => apacheRoute(route, trailingSlash));
}

export function replaceApacheBlock(
	source: string,
	block: string,
): string {
	const markers = [...source.matchAll(MARKER_PATTERN)];
	const newline = source.includes("\r\n") ? "\r\n" : "\n";
	const normalizedBlock = block.replace(/\r?\n/g, newline);

	function appendBlock(): string {
		if (!source) return `${normalizedBlock}${newline}`;
		const separator = source.endsWith(`${newline}${newline}`) ?
			"" :
			source.endsWith(newline) ?
			newline :
			`${newline}${newline}`;
		return `${source}${separator}${normalizedBlock}${newline}`;
	}

	if (!markers.length) return appendBlock();

	const [beginMarker, endMarker] = markers;
	if (
		markers.length !== 2 ||
		!beginMarker ||
		!endMarker ||
		(beginMarker[1] ?? beginMarker[2]) !== "BEGIN" ||
		(endMarker[1] ?? endMarker[2]) !== "END"
	) {
		throw new Error(
			`.htaccess must contain exactly one ${BEGIN_MARKER}/${END_MARKER} pair`,
		);
	}

	const start = beginMarker.index;
	const end = endMarker.index;
	if (start === undefined || end === undefined) return appendBlock();

	return (
		source.slice(0, start) +
		normalizedBlock +
		source.slice(end + endMarker[0].length)
	);
}

export function writeApacheConfig(
	webroot: Webroot,
	port: number = webroot.adapter === "apache-cgi" || webroot.adapter === "apache-static" ? webroot.port : apachePort(),
	routes: readonly ApacheRoute[] = [],
	rootIndex?: string,
): string {
	const filename = path.join(webroot.path, ".htaccess");
	let source = "";
	let mode: number | undefined;

	try {
		const stat = fs.lstatSync(filename);
		if (!stat.isFile()) {
			throw new Error(`${filename} is not a regular file`);
		}
		mode = stat.mode;
		source = fs.readFileSync(filename, "utf8");
	} catch (error) {
		if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
	}

	const updated = replaceApacheBlock(
		source,
		apacheBlock(port, routes, webroot.adapter === "node" ? "apache-proxy" : webroot.adapter, rootIndex),
	);
	if (updated === source) return filename;

	const temporary = path.join(
		webroot.path,
		`.htaccess.astralhp-${process.pid}.tmp`,
	);
	try {
		fs.writeFileSync(temporary, updated, { flag: "wx", mode });
		fs.renameSync(temporary, filename);
	} catch (error) {
		fs.rmSync(temporary, { force: true });
		throw error;
	}
	return filename;
}

export function generateApacheConfig(
	webroot: Webroot,
	resolved: AstralHPResolvedRoutes,
	port: number = webroot.adapter === "apache-cgi" || webroot.adapter === "apache-static" ? webroot.port : apachePort(),
): string {
	const routes = resolveApacheRoutes(resolved);
	const home = webroot.resolveDistFile("/");
	let rootIndex = home ? path.basename(home) : undefined;
	const existingHome = webroot.resolveStaticFile("/") || webroot.resolveFile("/index.php");
	if (!rootIndex && !existingHome && !resolved.routes.some(route => route.pattern === "/")) {
		const index = resolved.routes.find(route =>
			route.type === "endpoint" && route.isPrerendered && /^\/index\.[\w.-]+$/.test(route.pattern) &&
			webroot.resolveDistFile(route.pattern)
		);
		rootIndex = index?.pattern.slice(1);
	}
	return writeApacheConfig(webroot, port, routes, rootIndex);
}
